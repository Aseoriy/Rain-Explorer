#!/usr/bin/env python3
"""Convert the Windows build's WPF Lucide icon dictionary (Themes/Icons.xaml) into an
Avalonia resource dictionary of StreamGeometry entries.

WPF icons use PathGeometry/RectangleGeometry/EllipseGeometry/GeometryGroup. Avalonia's
path parser is stricter about implicit commands, so every figure is normalized into an
explicit SVG path string and grouped shapes are concatenated into one path.

Usage: convert_icons.py <path to WPF Icons.xaml> <output Icons.axaml>
"""
import re
import sys
import xml.etree.ElementTree as ET

WPF_NS = "{http://schemas.microsoft.com/winfx/2006/xaml/presentation}"
X_NS = "{http://schemas.microsoft.com/winfx/2006/xaml}"

ARG_COUNT = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
TOKEN = re.compile(r"[MmLlHhVvCcSsQqTtAaZz]|[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?")


def fmt(n: float) -> str:
    s = f"{n:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def normalize(figures: str) -> str:
    """Rewrite path mini-language with an explicit command before every argument group."""
    tokens = TOKEN.findall(figures)
    out = []
    i = 0
    cmd = None
    while i < len(tokens):
        tok = tokens[i]
        if tok.isalpha():
            cmd = tok
            i += 1
            if cmd in "Zz":
                out.append("Z")
                continue
        elif cmd is None:
            raise ValueError(f"Path data starts with a number: {figures!r}")
        n = ARG_COUNT[cmd.lower()]
        args = tokens[i:i + n]
        if len(args) < n:
            raise ValueError(f"Truncated arguments for {cmd} in {figures!r}")
        i += n
        if cmd.lower() == "a":
            rx, ry, rot, large, sweep, x, y = args
            out.append(f"{cmd}{fmt(float(rx))},{fmt(float(ry))} {fmt(float(rot))} "
                       f"{int(float(large))} {int(float(sweep))} {fmt(float(x))},{fmt(float(y))}")
        else:
            nums = [fmt(float(a)) for a in args]
            pairs = " ".join(",".join(nums[k:k + 2]) for k in range(0, len(nums), 2))
            out.append(f"{cmd}{pairs}")
        # SVG/WPF rule: extra coordinate pairs after a moveto are implicit linetos.
        if cmd == "M":
            cmd = "L"
        elif cmd == "m":
            cmd = "l"
    return " ".join(out)


def rect_path(rect: str, rx: float, ry: float) -> str:
    x, y, w, h = (float(v) for v in rect.replace(" ", ",").split(",") if v)
    rx = min(rx, w / 2)
    ry = min(ry, h / 2)
    if rx <= 0 or ry <= 0:
        return f"M{fmt(x)},{fmt(y)} H{fmt(x + w)} V{fmt(y + h)} H{fmt(x)} Z"
    return (f"M{fmt(x + rx)},{fmt(y)} H{fmt(x + w - rx)} "
            f"A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x + w)},{fmt(y + ry)} V{fmt(y + h - ry)} "
            f"A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x + w - rx)},{fmt(y + h)} H{fmt(x + rx)} "
            f"A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x)},{fmt(y + h - ry)} V{fmt(y + ry)} "
            f"A{fmt(rx)},{fmt(ry)} 0 0 1 {fmt(x + rx)},{fmt(y)} Z")


def ellipse_path(center: str, rx: float, ry: float) -> str:
    cx, cy = (float(v) for v in center.replace(" ", ",").split(",") if v)
    return (f"M{fmt(cx - rx)},{fmt(cy)} A{fmt(rx)},{fmt(ry)} 0 1 0 {fmt(cx + rx)},{fmt(cy)} "
            f"A{fmt(rx)},{fmt(ry)} 0 1 0 {fmt(cx - rx)},{fmt(cy)} Z")


def geometry(el: ET.Element) -> str:
    tag = el.tag.replace(WPF_NS, "")
    if tag == "PathGeometry":
        return normalize(el.attrib["Figures"])
    if tag == "RectangleGeometry":
        return rect_path(el.attrib["Rect"], float(el.attrib.get("RadiusX", 0)),
                         float(el.attrib.get("RadiusY", el.attrib.get("RadiusX", 0))))
    if tag == "EllipseGeometry":
        return ellipse_path(el.attrib["Center"], float(el.attrib["RadiusX"]),
                            float(el.attrib["RadiusY"]))
    if tag == "GeometryGroup":
        return " ".join(geometry(child) for child in el)
    raise ValueError(f"Unsupported geometry element: {tag}")


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    root = ET.parse(src).getroot()
    lines = [
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        "    <!-- Generated by tools/convert_icons.py from the Windows build's Themes/Icons.xaml.",
        "         Lucide line icons (ISC licensed), 24x24 geometry, looked up by \"Ic.<name>\".",
        "         Re-run the script instead of editing this file by hand. -->",
    ]
    count = 0
    for el in root:
        key = el.attrib.get(X_NS + "Key")
        if not key:
            continue
        lines.append(f'    <StreamGeometry x:Key="{key}">{geometry(el)}</StreamGeometry>')
        count += 1
    lines.append("</ResourceDictionary>")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {count} icons to {dst}")


if __name__ == "__main__":
    main()
